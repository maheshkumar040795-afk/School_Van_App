// Service worker: background push notifications (FCM) + offline app shell so the PWA can be installed.
importScripts('firebase-config.js');
importScripts('https://www.gstatic.com/firebasejs/10.12.2/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.12.2/firebase-messaging-compat.js');

if (self.FIREBASE_CONFIG && !String(self.FIREBASE_CONFIG.apiKey).startsWith('PASTE')) {
  firebase.initializeApp(self.FIREBASE_CONFIG);
  firebase.messaging(); // notifications with a "notification" payload are shown automatically
}

const CACHE = 'schoolvan-v1';
const SHELL = ['./', 'index.html', 'manifest.json', 'firebase-config.js', 'icons/icon-192.png', 'icons/icon-512.png'];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
// Network first, cache fallback (only for this site's own files)
self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== self.location.origin) return;
  e.respondWith(
    fetch(e.request)
      .then(res => { const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); return res; })
      .catch(() => caches.match(e.request).then(r => r || caches.match('index.html')))
  );
});
